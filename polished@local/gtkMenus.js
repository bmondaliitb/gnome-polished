import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import {surfacePalette, MATERIAL_STATES} from './materials.js';

const BEGIN = '/* BEGIN POLISHED GTK MENUS */';
const END = '/* END POLISHED GTK MENUS */';

export function withoutManagedMenuCss(text) {
    return text.replace(/\/\* BEGIN POLISHED GTK MENUS \*\/[\s\S]*?\/\* END POLISHED GTK MENUS \*\/\n?/g, '');
}
const OWNER = '/* Generated by Polished Materials. */';

export function gtkMenuCss(dark, opacity) {
    const palette = surfacePalette(dark);
    const bg = palette.background;
    const fg = palette.foreground;
    const alpha = Math.max(40, Math.min(100, opacity)) / 100;
    const item = 'popover.menu modelbutton, popover.menu button.model';
    const state = suffix => `popover.menu modelbutton${suffix}, popover.menu button.model${suffix}`;
    return `${OWNER}
/* Match native GTK4 item menus to Polished Shell menus. Preserve system high contrast. */
@media not (prefers-contrast: more) {
  popover.menu.background {
    --popover-bg-color: rgba(${bg},${alpha});
    --popover-fg-color: rgb(${fg});
    background-color: transparent;
    background-image: none;
    border: none;
    box-shadow: none;
    color: rgb(${fg});
  }
  popover.menu.background > contents {
    ${palette.fontStyle}
    background-color: rgba(${bg},${alpha});
    background-image: none;
    color: rgb(${fg});
    border: 1px solid rgba(${palette.edge});
    border-radius: 18px;
    padding: 8px;
    box-shadow: 0 8px 24px rgba(0,0,0,0.24);
  }
  popover.menu.background > arrow {
    background-color: rgba(${bg},${alpha}); background-image: none;
  }
  popover.menu > contents > stack,
  popover.menu > contents > scrolledwindow,
  popover.menu > contents > scrolledwindow > viewport,
  popover.menu > contents .background {
    background-color: transparent; background-image: none;
  }
  ${item} {
    border-radius: 12px; min-height: 32px; padding: 6px 12px;
    background-image: none; color: rgb(${fg});
  }
  ${state(':hover')} {
    background-color: rgba(${palette.highlight},${MATERIAL_STATES.hover});
  }
  ${state(':selected')}, ${state(':focus')} {
    background-color: rgba(${palette.selection},${MATERIAL_STATES.focus});
  }
  ${state(':active')} {
    background-color: rgba(${palette.selection},${MATERIAL_STATES.pressed});
  }
  ${state(':disabled')} { color: rgba(${fg},${MATERIAL_STATES.disabled}); }
  popover.menu modelbutton accelerator, popover.menu modelbutton .accelerator,
  popover.menu button.model accelerator, popover.menu button.model .accelerator {
    color: rgba(${fg},0.58);
  }
  popover.menu separator {
    background-color: rgba(${fg},0.14); min-height: 1px; margin: 6px 8px;
  }
}
`;

}

// Own one inline managed block, never replace the user's other GTK customization.
export class GtkMenuStyle {
    constructor(directory = GLib.build_filenamev([GLib.get_user_config_dir(), 'gtk-4.0'])) {
        this.directory = directory;
        this.main = Gio.File.new_for_path(GLib.build_filenamev([directory, 'gtk.css']));
        this.generated = Gio.File.new_for_path(GLib.build_filenamev([directory, 'polished-managed-menus.css']));
    }

    _read(file) {
        if (!file.query_exists(null)) return '';
        if (file.query_file_type(Gio.FileQueryInfoFlags.NOFOLLOW_SYMLINKS, null) === Gio.FileType.SYMBOLIC_LINK)
            throw new Error('Polished will not modify symlinked GTK stylesheet files.');
        const [, bytes] = file.load_contents(null);
        return new TextDecoder().decode(bytes);
    }

    _write(file, text) {
        if (this._read(file) === text) return;
        file.replace_contents(new TextEncoder().encode(text), null, false, Gio.FileCreateFlags.NONE, null);
    }

    apply(css) {
        if (css === null && !this.generated.query_exists(null) &&
            (!this.main.query_exists(null) || this.main.query_file_type(Gio.FileQueryInfoFlags.NOFOLLOW_SYMLINKS, null) === Gio.FileType.SYMBOLIC_LINK)) return;
        const main = this._read(this.main);
        const generated = this._read(this.generated);
        if (generated && !generated.startsWith(OWNER))
            throw new Error('Polished menu stylesheet path already contains an unowned file.');
        if (css !== null) {
            if (GLib.mkdir_with_parents(this.directory, 0o700) !== 0)
                throw new Error('Could not create GTK configuration directory.');
            this._write(this.generated, css);
            // Snap/portal theme forwarding may copy gtk.css but not adjacent files.
            // Keep the active rules self-contained instead of using a relative import.
            this._write(this.main, `${BEGIN}\n${css}\n${END}\n` + withoutManagedMenuCss(main));
        } else {
            const cleaned = withoutManagedMenuCss(main);
            if (main !== cleaned) this._write(this.main, cleaned);
            if (generated) this.generated.delete(null);
        }
    }
}
