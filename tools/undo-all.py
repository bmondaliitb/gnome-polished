#!/usr/bin/python3
"""Undo project appearance customizations. Preview by default; --apply changes them.
Run as the desktop user. Only the private GDM phase is elevated through sudo.
"""
import argparse
from dataclasses import dataclass
from datetime import datetime
import json
import os
from pathlib import Path
import re
import shutil
import stat
import subprocess
import sys
import tempfile

from gi.repository import Gio, GLib

UUIDS = ('polished@local', 'prism@local', 'polished-minimum@local')
APPEARANCE = {
    'org.gnome.desktop.interface': (
        'gtk-theme', 'icon-theme', 'cursor-theme', 'color-scheme', 'accent-color',
        'font-name', 'document-font-name', 'monospace-font-name',
        'text-scaling-factor', 'enable-animations', 'enable-hot-corners',
    ),
    'org.gnome.desktop.wm.preferences': ('button-layout', 'theme'),
    'org.gnome.desktop.background': ('picture-uri', 'picture-uri-dark', 'picture-options'),
    'org.gnome.shell.extensions.dash-to-dock': (
        'dock-position', 'extend-height', 'dock-fixed', 'autohide', 'intellihide',
        'manualhide', 'dash-max-icon-size', 'icon-size-fixed', 'transparency-mode',
        'background-opacity', 'custom-background-color', 'background-color',
        'running-indicator-style',
    ),
}
GENERATED = {
    'polished-managed-menus.css': '/* Generated by Polished Materials. */',
    'prism-managed-menus.css': '/* Generated by Prism Materials. */',
}


def run(*args, env=None, timeout=60):
    result = subprocess.run(args, env=env, text=True, capture_output=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError(f'{args[0]} failed: {(result.stderr or result.stdout).strip()}')
    return result.stdout


def clean_menu_css(text):
    # Refuse malformed/nested markers rather than consuming unrelated user CSS.
    names = ('POLISHED', 'PRISM')
    marker = re.compile(r'/\* (BEGIN|END) (POLISHED|PRISM) GTK MENUS \*/')
    opened = None
    for match in marker.finditer(text):
        kind, name = match.groups()
        if kind == 'BEGIN':
            if opened is not None:
                raise RuntimeError('Nested GTK menu markers; inspect gtk.css manually')
            opened = name
        elif opened != name:
            raise RuntimeError('Unmatched GTK menu marker; inspect gtk.css manually')
        else:
            opened = None
    if opened:
        raise RuntimeError('Incomplete GTK menu block; inspect gtk.css manually')
    for name in names:
        text = re.sub(r'/\* BEGIN ' + name + r' GTK MENUS \*/[\s\S]*?/\* END ' +
                      name + r' GTK MENUS \*/\n?', '', text)
    return text


def plain(path):
    if path.is_symlink():
        raise RuntimeError(f'Refusing linked path: {path}')


def gtk_plan(config):
    plans = []
    for toolkit in ('gtk-3.0', 'gtk-4.0'):
        directory = config / toolkit
        plain(directory)
        main = directory / 'gtk.css'
        plain(main)
        if main.exists():
            original = main.read_text()
            cleaned = clean_menu_css(original)
            # Also remove exact standalone imports of the owned generated files.
            # Only do this when the target file has the expected ownership header.
            for name, owner in GENERATED.items():
                generated = directory / name
                plain(generated)
                if generated.exists() and generated.read_text().startswith(owner):
                    cleaned = re.sub(r'(?m)^[ \t]*@import\s+(?:url\(\s*[\'"]?' + re.escape(name) +
                                     r'[\'"]?\s*\)|[\'"]' + re.escape(name) +
                                     r'[\'"])\s*;\s*\n?', '', cleaned)
            if cleaned != original:
                plans.append(('css', main, original, cleaned))
        for name, owner in GENERATED.items():
            generated = directory / name
            plain(generated)
            if generated.exists():
                if not generated.read_text().startswith(owner):
                    raise RuntimeError(f'Unrecognized generated file left untouched: {generated}')
                plans.append(('move', generated, None, None))
    return plans


def atomic_text(path, text):
    mode = stat.S_IMODE(path.stat().st_mode)
    fd, name = tempfile.mkstemp(prefix='.material-undo-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            os.fchmod(stream.fileno(), mode)
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def clean_gtk(config, backup):
    # Re-read after disabling extensions, which may restore their own CSS.
    for kind, path, original, cleaned in gtk_plan(config):
        destination = backup / path.parent.name / path.name
        destination.parent.mkdir(parents=True, exist_ok=True)
        if kind == 'css':
            shutil.copy2(path, destination)
            if path.read_text() != original:
                raise RuntimeError(f'Stylesheet changed during cleanup: {path}')
            atomic_text(path, cleaned)
        else:
            shutil.move(str(path), str(destination))
        print(f'Cleaned: {path}')


@dataclass(frozen=True)
class Companion:
    uuid: str
    state_name: str
    marker: str
    dropin_name: str


COMPANIONS = (
    Companion('polished-minimum-login@local', 'polished-minimum-login',
              '.polished-minimum-login-owned', 'zz-polished-minimum'),
    Companion('prism-login@local', 'prism-login-material',
              '.prism-login-owned', '99-prism-materials'),
)


@dataclass(frozen=True)
class SystemPaths:
    sources: Path = Path('/usr/share/gdm/dconf')
    database: Path = Path('/var/lib/gdm3/greeter-dconf-defaults')
    extensions: Path = Path('/usr/share/gnome-shell/extensions')
    state: Path = Path('/var/lib')
    backups: Path = Path('/var/lib/gnome-material-undo')


def companion_paths(companion, paths):
    return (paths.sources / companion.dropin_name, paths.extensions / companion.uuid,
            paths.state / companion.state_name)


def installed_companions(paths):
    return [companion for companion in COMPANIONS if
            any(path.exists() or path.is_symlink() for path in companion_paths(companion, paths))]


def validate_companion(companion, paths):
    dropin, extension, state_dir = companion_paths(companion, paths)
    for directory in (state_dir, extension):
        plain(directory)
        marker = directory / companion.marker
        if not directory.is_dir() or not marker.is_file():
            raise RuntimeError(f'Missing project ownership marker in {directory}; no system cleanup performed')
        if any(child.is_symlink() for child in directory.rglob('*')):
            raise RuntimeError(f'Linked installation contents: {directory}')
    plain(dropin)
    if not dropin.is_file():
        raise RuntimeError(f'Missing companion defaults: {dropin}')
    saved = json.loads((state_dir / 'settings.json').read_text())
    if saved.get('backend') != 'ubuntu-system-defaults' or saved.get('dropin') != dropin.read_text():
        raise RuntimeError(f'Edited/legacy login defaults: {dropin}; saved files retained for manual recovery')
    metadata = json.loads((extension / 'metadata.json').read_text())
    if metadata.get('uuid') != companion.uuid or metadata.get('session-modes') != ['gdm']:
        raise RuntimeError(f'Unrecognized login extension: {extension}')


def read_greeter(database, schema, key):
    # Read compiled system defaults through an isolated, empty user profile.
    with tempfile.TemporaryDirectory(prefix='material-undo-read-') as directory:
        root = Path(directory)
        profile = root / 'profile'
        profile.write_text(f'user-db:user\nfile-db:{database}\n')
        env = os.environ.copy()
        env.update(DCONF_PROFILE=str(profile), XDG_CONFIG_HOME=str(root),
                   XDG_RUNTIME_DIR=str(root), GSETTINGS_BACKEND='dconf')
        env.pop('DBUS_SESSION_BUS_ADDRESS', None)
        text = run('/usr/bin/gsettings', 'get', schema, key, env=env).strip()
        expected = GLib.VariantType.new('as') if text == '[]' else None
        return GLib.Variant.parse(expected, text, None, None).unpack()


def validate_greeter(database):
    enabled = read_greeter(database, 'org.gnome.shell', 'enabled-extensions')
    project_ids = set(UUIDS) | {companion.uuid for companion in COMPANIONS}
    if project_ids.intersection(enabled):
        raise RuntimeError('Other administrator GDM defaults still enable a project extension; no files changed')
    source = Gio.SettingsSchemaSource.get_default()
    schema = source.lookup('com.ubuntu.login-screen', True)
    if schema and schema.has_key('background-picture-uri'):
        uri = read_greeter(database, 'com.ubuntu.login-screen', 'background-picture-uri')
        if any('/' + companion.state_name + '/' in uri for companion in COMPANIONS):
            raise RuntimeError('Other administrator defaults still reference a custom login wallpaper; no files changed')


def undo_system(paths=SystemPaths(), compile_db=None, validate_db=None):
    companions = installed_companions(paths)
    if not companions:
        print('No project login-screen installations remain.')
        return None
    for companion in companions:
        validate_companion(companion, paths)
    plain(paths.database)
    if not paths.database.is_file():
        raise RuntimeError(f'Missing Ubuntu greeter database: {paths.database}')
    original = paths.database.stat()
    compile_db = compile_db or (lambda output, sources: run('/usr/bin/dconf', 'compile', str(output), str(sources)))
    validate_db = validate_db or validate_greeter
    # Compile/validate the complete future configuration before touching originals.
    with tempfile.TemporaryDirectory(prefix='.material-undo-', dir=paths.database.parent) as directory:
        temporary = Path(directory)
        candidate = temporary / 'sources'
        shutil.copytree(paths.sources, candidate, symlinks=True)
        for companion in companions:
            (candidate / companion.dropin_name).unlink()
        output = temporary / 'database'
        compile_db(output, candidate)
        validate_db(output)
        output.chmod(stat.S_IMODE(original.st_mode))
        os.chown(output, original.st_uid, original.st_gid)
        plain(paths.backups)
        paths.backups.mkdir(mode=0o700, parents=True, exist_ok=True)
        backup = paths.backups / datetime.now().strftime('%Y%m%d-%H%M%S-%f')
        backup.mkdir(mode=0o700)
        shutil.copy2(paths.database, backup / 'greeter-dconf-defaults.before')
        moves = []
        try:
            for companion in companions:
                for path in companion_paths(companion, paths):
                    # Absolute paths in the manifest retain their original destinations.
                    destination = backup / path.relative_to(path.anchor)
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    shutil.move(str(path), str(destination))
                    moves.append((path, destination))
            (backup / 'manifest.json').write_text(json.dumps(
                [{'original': str(a), 'saved': str(b)} for a, b in moves], indent=2) + '\n')
            # Commit last, on the same filesystem. Running GDM is never signalled.
            os.replace(output, paths.database)
        except Exception:
            for path, destination in reversed(moves):
                shutil.move(str(destination), str(path))
            raise
    print(f'Removed both installed project login companions. System backup: {backup}')
    return backup


def appearance_settings():
    source = Gio.SettingsSchemaSource.get_default()
    for schema_id, names in APPEARANCE.items():
        schema = source.lookup(schema_id, True)
        if schema is None:
            continue
        settings = Gio.Settings.new_full(schema, None, None)
        for key in names:
            if schema.has_key(key):
                yield schema_id, settings, key


def variant(value):
    return None if value is None else [value.get_type_string(), value.print_(True)]


def undo_user(apply=False, user_only=False):
    if os.geteuid() == 0:
        raise RuntimeError('Run this script as your desktop user, without sudo. It elevates only the GDM step.')
    config = Path(os.environ.get('XDG_CONFIG_HOME', str(Path.home() / '.config')))
    data = Path(os.environ.get('XDG_DATA_HOME', str(Path.home() / '.local/share')))
    state = Path(os.environ.get('XDG_STATE_HOME', str(Path.home() / '.local/state')))
    plain(config)
    plain(data / 'gnome-shell/extensions')
    profile = state / 'polished-minimum/profile.json'
    plain(profile)
    gtk_plan(config)  # Preflight all menu edits before changing anything.
    extension_dirs = []
    for uuid in UUIDS:
        directory = data / 'gnome-shell/extensions' / uuid
        plain(directory)
        if directory.exists():
            if json.loads((directory / 'metadata.json').read_text()).get('uuid') != uuid:
                raise RuntimeError(f'Unrecognized extension directory: {directory}')
            extension_dirs.append(directory)
    system_needed = installed_companions(SystemPaths())
    print('Plan: disable/archive Polished, Prism and Minimum desktop extensions; remove their GTK menu rules;')
    print('reset the listed theme/font/wallpaper/window-button/dock keys to distribution defaults;')
    print('clear only project preference namespaces and archive the Minimum profile backup.')
    print('Other extensions, app profiles, display settings and unrelated CSS are retained.')
    print('Login cleanup: ' + ('SKIPPED (--user-only)' if user_only else
          ', '.join(item.uuid for item in system_needed) or 'already absent'))
    for schema_id, settings, key in appearance_settings():
        print(f'  {schema_id} {key} -> {settings.get_default_value(key).print_(True)}')
    if not apply:
        print('Preview only. Run again with --apply to perform this plan.')
        return
    if not os.environ.get('DBUS_SESSION_BUS_ADDRESS'):
        raise RuntimeError('Run --apply inside your normal logged-in desktop terminal (session D-Bus is required).')
    backup = state / ('gnome-material-undo/' + datetime.now().strftime('%Y%m%d-%H%M%S-%f'))
    backup.mkdir(mode=0o700, parents=True)
    print(f'User backup: {backup}', flush=True)
    (backup / 'dconf.ini').write_text(run('/usr/bin/dconf', 'dump', '/'))
    os.chmod(backup / 'dconf.ini', 0o600)
    record = {f'{schema}/{key}': {'user': variant(settings.get_user_value(key)),
                               'effective': variant(settings.get_value(key))}
              for schema, settings, key in appearance_settings()}
    (backup / 'appearance.json').write_text(json.dumps(record, indent=2) + '\n')
    for toolkit in ('gtk-3.0', 'gtk-4.0'):
        directory = config / toolkit
        if directory.exists():
            shutil.copytree(directory, backup / 'before' / toolkit, symlinks=True)
    # Obtain administrator authorization before changing desktop preferences.
    if system_needed and not user_only:
        result = subprocess.run(['sudo', '/usr/bin/python3', str(Path(__file__).resolve()), '--system-phase'], check=False)
        if result.returncode:
            raise RuntimeError(f'Login cleanup failed (exit {result.returncode}); user changes not started. Backup: {backup}')
    enabled = set(run('gnome-extensions', 'list', '--enabled').splitlines())
    for uuid in UUIDS:
        if uuid in enabled:
            run('gnome-extensions', 'disable', uuid)
    shell = Gio.Settings.new('org.gnome.shell')
    for key in ('enabled-extensions', 'disabled-extensions'):
        current = shell.get_strv(key)
        filtered = [uuid for uuid in current if uuid not in UUIDS]
        if filtered != current and not shell.set_strv(key, filtered):
            raise RuntimeError(f'Could not clear project IDs from {key}')
    Gio.Settings.sync()
    clean_gtk(config, backup / 'removed-menu-rules')
    for directory in extension_dirs:
        destination = backup / 'extensions' / directory.name
        destination.parent.mkdir(exist_ok=True)
        shutil.move(str(directory), str(destination))
    if profile.exists():
        shutil.move(str(profile), str(backup / 'minimum-profile.before.json'))
    locked = []
    for schema_id, settings, key in appearance_settings():
        if settings.is_writable(key):
            settings.reset(key)
        else:
            locked.append(f'{schema_id} {key}')
    Gio.Settings.sync()
    for name in ('polished', 'prism', 'polished-minimum'):
        run('/usr/bin/dconf', 'reset', '-f', f'/org/gnome/shell/extensions/{name}/')
    # Settings changes/extension shutdown may rewrite a managed stylesheet.
    clean_gtk(config, backup / 'late-menu-rules')
    print(f'Desktop cleanup completed. User backup: {backup}')
    if user_only and system_needed:
        print('INCOMPLETE: login companions remain. Rerun --apply without --user-only to remove them.')
    if locked:
        raise RuntimeError('Administrator-locked preferences could not be reset: ' + '; '.join(locked))
    print('Save your work, then reboot to reload GDM and remove cached app/Shell styling. No reboot was performed.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true', help='Perform the rollback (default: preview only)')
    parser.add_argument('--user-only', action='store_true', help='Skip system login cleanup; no sudo request')
    parser.add_argument('--system-phase', action='store_true', help=argparse.SUPPRESS)
    args = parser.parse_args()
    try:
        if args.system_phase:
            if os.geteuid() != 0:
                raise RuntimeError('The internal system phase requires administrator privileges')
            undo_system()
        else:
            undo_user(args.apply, args.user_only)
    except (RuntimeError, OSError, ValueError, subprocess.SubprocessError, GLib.Error) as error:
        print(f'Undo stopped: {error}', file=sys.stderr)
        print('No GDM restart/reboot was requested. Keep the reported backups; earlier completed steps may remain applied.', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
